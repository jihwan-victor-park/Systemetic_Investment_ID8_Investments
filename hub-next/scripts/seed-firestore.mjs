// Pulls the lines between two predicates (inclusive start, exclusive end) out
// of a line array, starting the search at `from`.
function linesBetween(lines, from, startsWith, stopWhen) {
  let i = from;
  while (i < lines.length && !lines[i].startsWith(startsWith)) i++;
  if (i >= lines.length) return { text: '', next: from };
  const collected = [];
  i++; // skip the marker line itself
  while (i < lines.length && !stopWhen(lines[i])) {
    collected.push(lines[i]);
    i++;
  }
  return { text: collected.join('\n').trim(), next: i };
}

function parseScreenChunk(chunk) {
  const lines = chunk.split('\n');

  const heading = lines[0].match(/^## Screen — (\d{4}-\d{2}-\d{2})(?: · (.+))?$/);
  const date = heading[1];
  const roundStage = heading[2] ? heading[2].trim() : null;

  const plain = chunk.replace(/\*\*/g, '');
  const fitMatch = plain.match(/Fit score: ([\d.]+) \/ 4\.0(?: \(raw ([\d.]+)\))?(?: — (.+))?/);
  const fitScore = fitMatch ? parseFloat(fitMatch[1]) : null;
  const rawScore = fitMatch && fitMatch[2] ? parseFloat(fitMatch[2]) : null;
  const verdict = fitMatch && fitMatch[3] ? fitMatch[3].trim().split('\n')[0].trim() : null;

  const hardAutoPassMatch = chunk.match(/\*(Hard auto-pass:[^*]+)\*/);
  const hardAutoPassNote = hardAutoPassMatch ? hardAutoPassMatch[1].trim() : null;

  // Dimension table: from the header row to the first line that isn't a `|` row.
  const tableHeaderIdx = lines.findIndex((l) => l.trim().startsWith('| Dimension'));
  const dimensions = [];
  if (tableHeaderIdx >= 0) {
    let i = tableHeaderIdx + 2; // skip header + separator row
    while (i < lines.length && lines[i].trim().startsWith('|')) {
      const cols = lines[i].split('|').slice(1, -1).map((c) => c.trim());
      if (cols.length >= 3) {
        const scoreMatch = cols[1].match(/(\d+)/);
        dimensions.push({ name: cols[0], score: scoreMatch ? parseInt(scoreMatch[1], 10) : null, evidence: cols.slice(2).join(' | ') });
      }
      i++;
    }
  }

  const { text: rationale } = linesBetween(lines, 0, '**Rationale**', (l) => l.trim().startsWith('*Confidence:'));
  const confidenceMatch = chunk.match(/\*Confidence: (\w+)\*/);
  const confidence = confidenceMatch ? confidenceMatch[1] : null;

  const sourcesHeaderIdx = lines.findIndex((l) => l.trim() === '**Sources**');
  const sources = [];
  if (sourcesHeaderIdx >= 0) {
    // Blank lines separate "**Sources**" from the list and the list from the
    // trailing "---", so skip past them rather than stopping on the first one.
    let i = sourcesHeaderIdx + 1;
    while (i < lines.length && lines[i].trim() !== '---') {
      const m = lines[i].match(/^(\d+)\.\s+\[(.+?)\]\((.+?)\)/);
      if (m) sources.push({ number: parseInt(m[1], 10), url: m[3] });
      i++;
    }
  }

  return { date, roundStage, fitScore, rawScore, verdict, hardAutoPassNote, dimensions, rationale, confidence, sources };
}

function parseCompanyFile(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  const { data, content } = matter(raw);
  const start = content.indexOf('<!-- SCREENS:START -->');
  const end = content.indexOf('<!-- SCREENS:END -->');
  const block = start >= 0 && end >= 0 ? content.slice(start, end) : content;
  const chunks = block.split(/(?=^## Screen — )/m).filter((c) => c.trim().startsWith('## Screen'));
  const screens = chunks.map(parseScreenChunk);
  return {
    slug: data.company_id,
    // Keep the full frontmatter title verbatim (e.g. "Pocket (Business/Productivity
    // Software)") — that's what Docusaurus's autogenerated sidebar and the company
    // page's own H1 actually show. The shorter "Pocket" form only appears in the
    // hand-authored research/index.md table, which is a separate, deliberately
    // shortened label — see the COMPANY_SHORT_NAME override on the research index page.
    name: data.title,
    website: data.website,
    screens,
  };
}

async function seedCompanies() {
  const files = fs.readdirSync(COMPANIES_DIR).filter((f) => f.endsWith('.md'));
  for (const file of files) {
    const company = parseCompanyFile(path.join(COMPANIES_DIR, file));
    console.log(`companies/${company.slug} — ${company.name} (${company.screens.length} screen${company.screens.length === 1 ? '' : 's'})`);
    await db.collection('companies').doc(company.slug).set({
      name: company.name,
      website: company.website,
      updatedAt: new Date(),
    });
    for (const screen of company.screens) {
      await db
        .collection('companies')
        .doc(company.slug)
        .collection('screens')
        .doc(screen.date)
        .set({ ...screen, docxPath: `/research/companies/${company.slug}.docx` });
    }
  }
}

