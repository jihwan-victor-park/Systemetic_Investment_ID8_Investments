async function main() {
  const col = db.collection('dealResearchDecks');
  for (const deck of NEW_DEAL_SCREENS) {
    const existing = await col.where('companyName', '==', deck.companyName).limit(1).get();
    if (!existing.empty) {
      const ref = existing.docs[0].ref;
      await ref.set(deck, { merge: true });
      console.log(`dealResearchDecks/${ref.id}  ${deck.companyName} — updated existing entry`);
    } else {
      const ref = await col.add({ ...deck, createdAt: new Date() });
      console.log(`dealResearchDecks/${ref.id}  ${deck.companyName} — new`);
    }
  }
  console.log(`\nDone. ${NEW_DEAL_SCREENS.length} deal screening entries processed.`);
}

main().then(() => process.exit(0)).catch((err) => { console.error(err); process.exit(1); });
